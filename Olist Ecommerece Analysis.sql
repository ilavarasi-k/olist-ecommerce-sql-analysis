/*1. TOTAL ORDERS*/
SELECT 
  COUNT(*) AS TOTAL_ORDERS FROM OLIST_ORDERS;

/* 2. ORDER STATUS ANALYSIS */

SELECT
  ORDER_STATUS,
  COUNT(*) AS TOTAL_ORDERS
FROM OLIST_ORDERS
GROUP BY ORDER_STATUS
ORDER BY TOTAL_ORDERS DESC;

/* 3. CUSTOMER STATE ANALYSIS */

SELECT 
  CUSTOMER_STATE,
  COUNT(*) AS TOTAL_CUSTOMERS
FROM OLIST_CUSTOMER
GROUP BY CUSTOMER_STATE
ORDER BY TOTAL_CUSTOMERS DESC;

/* 4. CUSTOMER CITY ANALYSIS */

SELECT 
  CUSTOMER_CITY,
  COUNT(*) AS TOTAL_CUSTOMER
FROM OLIST_CUSTOMER
GROUP BY CUSTOMER_CITY
ORDER BY TOTAL_CUSTOMER DESC;

/* 4. TOP 10 ORDERS BY VALUE */

SELECT *
  FROM(
   SELECT ORDER_ID,
   ROUND(SUM(PRICE),2) AS
ORDER_VALUE
 FROM OLIST_ORDER_ITEMS
 GROUP BY ORDER_ID
 ORDER BY ORDER_VALUE DESC )
 WHERE ROWNUM <= 10;
 
 
 /* 5. MONTHLY SALES ANALYSIS */
 
 SELECT
   TO_CHAR(
    O.ORDER_PURCHASE_TIMESTAMP,'YYYY-MM'
    ) AS SALES_MONTH,
   ROUND(SUM(I.PRICE),2) AS TOTAL_SALES
FROM OLIST_ORDERS O
JOIN OLIST_ORDER_ITEMS I
  ON O.ORDER_ID = I.ORDER_ID
  GROUP BY TO_CHAR (O.ORDER_PURCHASE_TIMESTAMP,'YYYY-MM')
  
ORDER BY SALES_MONTH;


/* 6. TOP 10 PRODUCT CATEGORIES BY SALES */
 
 SELECT * FROM (SELECT
 P.PRODUCT_CATEGORY_NAME,
 ROUND(SUM(I.PRICE),2) AS TOTAL_SALES
 FROM OLIST_PRODUCTS P
 JOIN OLIST_ORDER_ITEMS I
  ON P.PRODUCT_ID =I.PRODUCT_ID
 GROUP BY P.PRODUCT_CATEGORY_NAME
 ORDER BY TOTAL_SALES DESC
 )
 WHERE ROWNUM <=10;
 
/*7. PAYMENT TYPE ANALYSIS*/

 SELECT PAYMENT_TYPE,
 COUNT (*) AS TOTAL_PAYMENTS,
 ROUND (SUM(PAYMENT_VALUE),2) AS
 TOTAL_PAYMENT_VALUE
 FROM OLIST_ORDER_PAYMENTS
 GROUP BY PAYMENT_TYPE
 ORDER BY TOTAL_PAYMENT_VALUE DESC;
 
 
 /* 8. PAYMENT INSTALLMENT ANALYSIS */
 
 SELECT 
  PAYMENT_INSTALLMENTS,
  COUNT(*) AS TOTAL_PAYMENTS,
  ROUND(AVG(PAYMENT_VALUE),2 )AS
AVG_PAYMENT_VALUE
 FROM OLIST_ORDER_PAYMENTS
 GROUP BY   PAYMENT_INSTALLMENTS
 ORDER BY   PAYMENT_INSTALLMENTS;


/* 9. CUSTOMER ORDER ANALYSIS BY STATE */
SELECT
 C.CUSTOMER_STATE,
 COUNT(O.ORDER_ID) AS TOTAL_ORDERS
FROM OLIST_ORDERS O
JOIN OLIST_CUSTOMER C
  ON O.CUSTOMER_ID =C.CUSTOMER_ID
GROUP BY C.CUSTOMER_STATE
ORDER BY TOTAL_ORDERS DESC;


/* 10, ORDER ITEM PRICE ANALYSIS */

SELECT
  COUNT(*) AS TOTAL_ORDER_ITEMS,
  ROUND(SUM(PRICE),2)AS TOTAL_ITEM_VALUE,
  ROUND(AVG(PRICE),2)AS AVG_ITEM_PRICE,
  ROUND(MAX(PRICE),2)AS MAX_ITEM_PRICE,
  ROUND(MIN(PRICE),2)AS MIN_ITEM_PRICE
FROM OLIST_ORDER_ITEMS;


/* 11. SHIPPING COST ANALYSIS */

SELECT
  ROUND(SUM(FREIGHT_VALUE),2)
   AS TOTAL_FREIGHT_VALUE,
  ROUND(AVG(FREIGHT_VALUE),2)
   AS AVG_FREIGHT_VALUE
FROM OLIST_ORDER_ITEMS;


/* 12. PAYMENT TYPE DISTRIBUTION */
SELECT
 PAYMENT_TYPE,
 COUNT(*) AS PAYMENT_RECORDS
FROM OLIST_ORDER_PAYMENTS
GROUP BY PAYMENT_TYPE
ORDER BY PAYMENT_RECORDS DESC;


/* 13. ORDER STATUS PERCENTAGE */
SELECT
  ORDER_STATUS,
  COUNT(*)AS TOTAL_ORDERS,
  ROUND(COUNT(*) *100.0 /
   (SELECT COUNT(*) FROM OLIST_ORDERS),2) ASORDER_PERCENTAGE
FROM OLIST_ORDERS
GROUP BY ORDER_STATUS
ORDER BY TOTAL_ORDERS DESC;


/* 14. TOP 10 PRODUCTS BY NUMBER OF ITEMS SLOD */
  

SELECT * FROM
( 
SELECT
   PRODUCT_ID,
   COUNT(*) AS ITEMS_SOLD,
   ROUND(SUM(PRICE),2) AS
TOTAL_SALES
  FROM OLIST_ORDER_ITEMS
  GROUP BY PRODUCT_ID
  ORDER BY ITEMS_SOLD DESC )
WHERE ROWNUM <=10;


/* 15. AVERAGE ORDER VALUE */

SELECT
  ROUND(AVG(ORDER_VALUE),2) AS AVG_ORDER_VALUE
FROM(SELECT 
  ORDER_ID,
  SUM(PRICE) AS ORDER_VALUE
FROM OLIST_ORDER_ITEMS
GROUP BY ORDER_ID
);










 

 
 
 
 
 
 
 
 
 
 
 
 
 
  
 
 
 
 
 
 
 
 
 
 
 
 
 
 
 
 
 
 
 
 
 